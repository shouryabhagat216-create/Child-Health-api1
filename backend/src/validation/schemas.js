const { z } = require('zod');

const INDIAN_STATES_AND_UTS = [
  'Andhra Pradesh', 'Arunachal Pradesh', 'Assam', 'Bihar', 'Chhattisgarh', 'Goa', 'Gujarat',
  'Haryana', 'Himachal Pradesh', 'Jharkhand', 'Karnataka', 'Kerala', 'Madhya Pradesh',
  'Maharashtra', 'Manipur', 'Meghalaya', 'Mizoram', 'Nagaland', 'Odisha', 'Punjab',
  'Rajasthan', 'Sikkim', 'Tamil Nadu', 'Telangana', 'Tripura', 'Uttar Pradesh', 'Uttarakhand',
  'West Bengal',
  // Union territories
  'Andaman and Nicobar Islands', 'Chandigarh', 'Dadra and Nagar Haveli and Daman and Diu',
  'Delhi', 'Jammu and Kashmir', 'Ladakh', 'Lakshadweep', 'Puducherry',
];

const CONSENT_STATUSES = ['pending', 'granted', 'revoked'];
const REMINDER_STATUSES = ['scheduled', 'sent', 'completed', 'cancelled'];

const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/;

// "2024-02-30" matches the regex but is not a real date, so round-trip it.
function isRealDate(value) {
  if (!ISO_DATE.test(value)) return false;
  const parsed = new Date(`${value}T00:00:00Z`);
  return !Number.isNaN(parsed.getTime()) && parsed.toISOString().slice(0, 10) === value;
}

const todayUtc = () => new Date().toISOString().slice(0, 10);

const requiredString = (max = 100) =>
  z
    .string({ required_error: 'is required', invalid_type_error: 'must be a string' })
    .trim()
    .min(1, 'must not be empty')
    .max(max, `must be at most ${max} characters`);

const isoDate = z
  .string({ required_error: 'is required', invalid_type_error: 'must be a string' })
  .superRefine((value, ctx) => {
    if (!ISO_DATE.test(value)) {
      ctx.addIssue({ code: z.ZodIssueCode.custom, message: 'must be in YYYY-MM-DD format' });
      return;
    }
    if (!isRealDate(value)) {
      ctx.addIssue({ code: z.ZodIssueCode.custom, message: 'must be a valid calendar date' });
    }
  });

const enumOf = (values, message) => z.enum(values, { errorMap: () => ({ message }) });

// Child ID is generated by the server, so clients may not send it (.strict() rejects unknown keys).
const registerChildSchema = z
  .object({
    name: requiredString(100),
    dateOfBirth: isoDate.refine(
      (value) => !isRealDate(value) || value <= todayUtc(),
      'must not be in the future'
    ),
    guardianName: requiredString(100),
    state: enumOf(INDIAN_STATES_AND_UTS, 'must be a valid Indian state or union territory'),
    consentStatus: enumOf(CONSENT_STATUSES, `must be one of: ${CONSENT_STATUSES.join(', ')}`),
  })
  .strict();

const createReminderSchema = z
  .object({
    childId: z
      .string({ required_error: 'is required', invalid_type_error: 'must be a string' })
      .uuid('must be a valid UUID'),
    vaccineName: requiredString(100),
    dueDate: isoDate,
    // Optional; a new reminder starts as "scheduled".
    reminderStatus: enumOf(REMINDER_STATUSES, `must be one of: ${REMINDER_STATUSES.join(', ')}`).default(
      'scheduled'
    ),
  })
  .strict();

const childIdParamSchema = z.object({
  id: z.string().uuid('must be a valid UUID'),
});

module.exports = {
  registerChildSchema,
  createReminderSchema,
  childIdParamSchema,
  INDIAN_STATES_AND_UTS,
  CONSENT_STATUSES,
  REMINDER_STATUSES,
};
